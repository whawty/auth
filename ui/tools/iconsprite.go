//go:build ignore

// iconsprite builds the SVG sprite of the web interface from the icons of the
// lucide-static npm package. It is not part of the build, use `make ui-icons`
// which downloads the package and runs
//
//	go run ui/tools/iconsprite.go -src <unpacked package> -out ui/assets/vendor/lucide/icons.svg <icon-name>...
//
// The Lucide version and the list of icons are set in the Makefile. Every icon
// becomes a <symbol> with the name of the icon as id, the web interface uses
// them with <svg><use href="vendor/lucide/icons.svg#<icon-name>"/></svg>.
package main

import (
	"encoding/json"
	"encoding/xml"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type icon struct {
	Attrs []xml.Attr `xml:",any,attr"`
	Inner string     `xml:",innerxml"`
}

// attributes of the root element which are not copied to the <symbol>
var dropAttrs = map[string]bool{"class": true, "width": true, "height": true, "xmlns": true}

var betweenTagsRe = regexp.MustCompile(`>\s+<`)

func readIcon(src, name string) (string, error) {
	data, err := os.ReadFile(filepath.Join(src, "icons", name+".svg"))
	if err != nil {
		return "", err
	}
	var ic icon
	if err := xml.Unmarshal(data, &ic); err != nil {
		return "", fmt.Errorf("%s: %v", name, err)
	}

	var attrs []string
	for _, a := range ic.Attrs {
		if a.Name.Space != "" || dropAttrs[a.Name.Local] {
			continue
		}
		var value strings.Builder
		if err := xml.EscapeText(&value, []byte(a.Value)); err != nil {
			return "", err
		}
		attrs = append(attrs, fmt.Sprintf(`%s="%s"`, a.Name.Local, value.String()))
	}
	inner := betweenTagsRe.ReplaceAllString(strings.TrimSpace(ic.Inner), "><")
	return fmt.Sprintf(`<symbol id="%s" %s>%s</symbol>`, name, strings.Join(attrs, " "), inner), nil
}

func lucideVersion(src string) string {
	data, err := os.ReadFile(filepath.Join(src, "package.json"))
	if err != nil {
		return "unknown version"
	}
	var pkg struct {
		Name    string `json:"name"`
		Version string `json:"version"`
	}
	if err := json.Unmarshal(data, &pkg); err != nil || pkg.Name != "lucide-static" {
		return "unknown version"
	}
	return pkg.Version
}

func main() {
	src := flag.String("src", "", "directory of the unpacked lucide-static package (contains icons/)")
	out := flag.String("out", "", "file to write the sprite to")
	flag.Parse()
	names := flag.Args()
	if *src == "" || *out == "" || len(names) == 0 {
		fmt.Fprintln(os.Stderr, "usage: go run ui/tools/iconsprite.go -src <lucide-static> -out <sprite.svg> <icon-name>...")
		os.Exit(2)
	}
	sort.Strings(names)

	var sprite strings.Builder
	sprite.WriteString(`<svg xmlns="http://www.w3.org/2000/svg">` + "\n")
	fmt.Fprintf(&sprite, "<!-- Lucide %s (https://lucide.dev), ISC License, some icons MIT License, see LICENSE.\n", lucideVersion(*src))
	sprite.WriteString("     Generated by ui/tools/iconsprite.go, do not edit. -->\n")
	for _, name := range names {
		symbol, err := readIcon(*src, name)
		if err != nil {
			fmt.Fprintln(os.Stderr, "error:", err)
			os.Exit(1)
		}
		sprite.WriteString(symbol + "\n")
	}
	sprite.WriteString("</svg>\n")

	if err := os.WriteFile(*out, []byte(sprite.String()), 0644); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}
